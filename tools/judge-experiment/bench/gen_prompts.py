# Regenerates src/core/JudgePrompts.cpp from prompts.py: the adopted words
# (FINAL v8, QUERY v4, PICK v3) and their answer schemas, made strict as the
# API wants them. Run after a change to the words, which is a change to
# docs/import-rules-judge.html first.
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import prompts, claude

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(f'{HERE}/../../../src/core/JudgePrompts.cpp')


def lit(s):
    assert ')__"' not in s
    return 'R"__(' + s + ')__"'


out = ['// Generated by tools/judge-experiment/bench/gen_prompts.py from prompts.py: the words',
       '// the judge is given (docs/import-rules-judge.html, K1–K3) and the shapes of its answers.',
       '// Do not edit: a change to the words is a change to the page first.',
       '#include "core/Judge.h"', '',
       'namespace JudgeWords {', '',
       'const char *const kQueryWords = ' + lit(prompts.QUERY['v4']) + ';', '',
       'const char *const kPickWords = ' + lit(prompts.PICK['v3']) + ';', '',
       'const char *const kVerdictWords = ' + lit(prompts.FINAL['v8']) + ';', '',
       'const char *const kQuerySchema = ' + lit(json.dumps(claude.strict(prompts.SCHEMA_QUERY), ensure_ascii=False)) + ';', '',
       'const char *const kPickSchema = ' + lit(json.dumps(claude.strict(prompts.SCHEMA_PICK), ensure_ascii=False)) + ';', '',
       'const char *const kVerdictSchema = ' + lit(json.dumps(claude.strict(prompts.SCHEMA_FINAL), ensure_ascii=False)) + ';', '',
       '} // namespace JudgeWords', '']
open(OUT, 'w').write('\n'.join(out))
print(f'wrote {OUT}')
